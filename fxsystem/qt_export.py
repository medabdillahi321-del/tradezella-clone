"""Export a shadow run for review in Quant Terminal.

Writes, into data/exports/<run>/:
- bars_<NAME>.csv        1-minute bars (time, open, high, low, close, volume). Prices are
                         the MID (halfway between bid and ask); the system itself trades on
                         bid and ask. Opens in Quant Terminal as CSV:<NAME>, and any longer
                         timeframe is built from it.
- shadow-trades-<id>.js  a Quant Terminal custom indicator: entry and exit arrows, plus the
                         stop and target lines while each trade is open. Display only.
- signal_<id>.csv        time, position (1 long, -1 short, 0 flat) for Quant Terminal's
                         strategy tester. Approximate: the tester only trades at bar opens,
                         so a stop hit inside a bar exits one bar later there.
- trades.csv             every virtual trade, one row each, for reading or a spreadsheet.
- HOW_TO_OPEN.txt        the steps.

Nothing here changes the run's log; the export can be regenerated at any time.
"""

from __future__ import annotations

import csv
import json
from datetime import datetime, timedelta, timezone
from decimal import Decimal
from pathlib import Path

from fxsystem.clock import NEW_YORK
from fxsystem.storage import LocalLog

UTC = timezone.utc


def _secs(iso: str) -> int:
    return int(datetime.fromisoformat(iso.replace("Z", "+00:00")).timestamp())


def _iso(dt: datetime) -> str:
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")


def load_run(log_path: str | Path) -> dict:
    """Trades from a shadow run log, joined with their entry details."""
    with LocalLog(log_path) as log:
        start = log.events("system.shadow_start")
        if not start:
            raise ValueError("This log is not a shadow run (no system.shadow_start event)")
        entries = {e.payload["intent_id"]: e.payload for e in log.events("shadow.fill") if e.payload["action"] == "entry"}
        moves = {}
        for e in log.events("shadow.stop_moved"):
            moves.setdefault(e.payload["intent_id"], []).append(e.ts_utc[:19] + "Z")
        trades = []
        for e in log.events("shadow.trade_closed"):
            p = e.payload
            ent = entries.get(p["intent_id"], {})
            trades.append({**p, "stop": ent.get("stop"), "target": ent.get("target"),
                           "stop_moved": moves.get(p["intent_id"], [])})
        open_end = [e.payload for e in log.events("shadow.open_at_end")]
        return {"run_id": start[0].payload["run_id"], "config": start[0].payload, "trades": trades,
                "open_at_end": open_end}


def write_bars(bars: list[dict], path: Path) -> int:
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["time", "open", "high", "low", "close", "volume"])
        for b in bars:
            mid = {k: (b["bid"][k] + b["ask"][k]) / 2 for k in "ohlc"}
            w.writerow([_iso(b["start"]), *(f"{mid[k]:.6f}" for k in "ohlc"), b.get("volume", 0)])
    return len(bars)


def write_signal(trades: list[dict], path: Path) -> int:
    rows: dict[int, int] = {}
    # In time order: each trade sets its position on the bar whose close produced the idea and
    # goes flat on the bar in which it exited; a later trade starting on that bar overrides the flat.
    for t in sorted(trades, key=lambda x: x["entry_time"]):
        rows[_secs(t["entry_time"]) - 60] = 1 if t["side"] == "buy" else -1
        rows[_secs(t["exit_time"]) - 60] = 0
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["time", "position"])
        for s in sorted(rows):
            w.writerow([_iso(datetime.fromtimestamp(s, UTC)), rows[s]])
    return len(rows)


def write_trades_csv(trades: list[dict], path: Path) -> None:
    def ny(iso: str) -> str:
        return datetime.fromisoformat(iso.replace("Z", "+00:00")).astimezone(NEW_YORK).strftime("%Y-%m-%d %H:%M")

    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["trade", "side", "units", "entry_new_york", "entry_utc", "entry_price", "stop", "target",
                    "exit_new_york", "exit_utc", "exits", "pnl_usd", "r", "stop_moved_to_entry", "ambiguous_bar"])
        for i, t in enumerate(sorted(trades, key=lambda x: x["entry_time"]), 1):
            exits = " | ".join(f"{x['why']} {x['units']} @ {x['price']}" for x in t["exits"])
            w.writerow([i, t["side"], t["units"], ny(t["entry_time"]), t["entry_time"], t["entry_price"],
                        t["stop"], t["target"], ny(t["exit_time"]), t["exit_time"], exits, t["pnl"], t["r"],
                        "yes" if t["stop_moved"] else "", "yes" if t["ambiguous_bars"] else ""])


INDICATOR_TEMPLATE = """// Generated by the FX shadow system from run {run_id}.
// DISPLAY ONLY: shows virtual (shadow) trades on the chart. It decides nothing.
// Arrows: entries (green up = buy, red down = sell). Circles: exits, labelled with the result in R.
// Lines: the initial stop (red) and target (green) while each trade was open.
const TRADES = {trades_json};

export default {{
  name: {name_json},
  overlay: true,
  inputs: [],
  outputs: [
    {{ key: 'stop', label: 'Shadow stop', kind: 'line', color: '#ef5350', lineWidth: 1 }},
    {{ key: 'target', label: 'Shadow target', kind: 'line', color: '#26a69a', lineWidth: 1 }},
  ],
  calc(bars, p, ta) {{
    const n = bars.length;
    const stop = new Array(n).fill(NaN);
    const target = new Array(n).fill(NaN);
    const markers = [];
    if (!n) return {{ stop, target, markers }};
    const last = bars[n - 1].time;
    // Index of the bar containing time t (the last bar starting at or before t), or -1.
    const at = (t) => {{
      if (t < bars[0].time) return -1;
      let lo = 0, hi = n - 1;
      while (lo < hi) {{ const mid = (lo + hi + 1) >> 1; if (bars[mid].time <= t) lo = mid; else hi = mid - 1; }}
      return lo;
    }};
    for (const tr of TRADES) {{
      if (tr.entry > last + 86400 || tr.exit < bars[0].time) continue;
      const a = at(tr.entry), b = at(tr.exit);
      if (a >= 0) {{
        for (let i = a; i <= (b >= 0 ? b : a); i++) {{ stop[i] = tr.stop; if (tr.target != null) target[i] = tr.target; }}
        markers.push(tr.side === 'buy'
          ? {{ time: bars[a].time, position: 'belowBar', shape: 'arrowUp', color: '#26a69a', text: 'Buy' }}
          : {{ time: bars[a].time, position: 'aboveBar', shape: 'arrowDown', color: '#ef5350', text: 'Sell' }});
      }}
      if (b >= 0) {{
        markers.push({{ time: bars[b].time, position: tr.side === 'buy' ? 'aboveBar' : 'belowBar', shape: 'circle',
          color: tr.r > 0 ? '#26a69a' : '#ef5350', text: (tr.r > 0 ? '+' : '') + tr.r.toFixed(2) + 'R ' + tr.why }});
      }}
    }}
    markers.sort((x, y) => x.time - y.time);
    return {{ stop, target, markers }};
  }},
}};
"""


def write_indicator(trades: list[dict], run_id: str, short: str, path: Path) -> None:
    data = [{
        "entry": _secs(t["entry_time"]),
        "exit": _secs(t["exit_time"]) - 60,   # the bar in which the exit happened
        "side": t["side"],
        "stop": float(Decimal(t["stop"])) if t["stop"] else None,
        "target": float(Decimal(t["target"])) if t["target"] else None,
        "r": float(Decimal(t["r"])),
        "why": t["exits"][-1]["why"] if t["exits"] else "",
    } for t in sorted(trades, key=lambda x: x["entry_time"])]
    path.write_text(INDICATOR_TEMPLATE.format(
        run_id=run_id, trades_json=json.dumps(data, separators=(",", ":")),
        name_json=json.dumps(f"Shadow trades {short}")), encoding="utf-8")


HOW_TO = """How to open this shadow run in Quant Terminal
==============================================

Run: {run_id}
Trades: {n_trades}    Bars: {n_bars}

1. Price chart
   Strategy tester tab -> "Your own data" -> Bars -> choose {bars_file}
   Then type CSV:{name} in the symbol box. It opens on 1-minute bars; pick any longer
   timeframe and Quant Terminal builds it from them.
   (Prices are the mid: halfway between OANDA's bid and ask.)

2. Trade arrows and stop/target lines
   Copy {indicator_file} into Quant Terminal's "custom" folder, or open the Indicator editor
   tab, paste the file's contents and press Save. Then add the indicator
   "Shadow trades {short}" to the CSV:{name} chart.

3. Optional: Quant Terminal's own strategy tester as a rough second opinion
   Strategy tester tab -> "Your own data" -> Signal -> choose {signal_file}
   It trades only at bar opens, so its results will differ a little from the shadow run.
   Use the shadow run's numbers (trades.csv) as the reference.

4. trades.csv lists every virtual trade, with New York and UTC times.

These are virtual trades from the shadow system. They are not real fills and not proof of an edge.
"""


def export_run(log_path: str | Path, bars: list[dict], out_root: str | Path, name: str = "EURUSD_M1") -> Path:
    run = load_run(log_path)
    short = run["run_id"].rsplit("-", 1)[-1][:8]
    out = Path(out_root) / "exports" / run["run_id"]
    out.mkdir(parents=True, exist_ok=True)
    files = {
        "bars_file": f"bars_{name}.csv",
        "indicator_file": f"shadow-trades-{short}.js",
        "signal_file": f"signal_{short}.csv",
    }
    n_bars = write_bars(bars, out / files["bars_file"])
    write_indicator(run["trades"], run["run_id"], short, out / files["indicator_file"])
    write_signal(run["trades"], out / files["signal_file"])
    write_trades_csv(run["trades"], out / "trades.csv")
    (out / "HOW_TO_OPEN.txt").write_text(HOW_TO.format(
        run_id=run["run_id"], n_trades=len(run["trades"]), n_bars=n_bars, name=name, short=short, **files),
        encoding="utf-8")
    return out
